/**
 * Pure helpers behind infra/live-week/cutover.sh and run-week.sh (the 11/30-night cutover to the
 * live week). The shell scripts own the order of operations; what can be got wrong by a typo or an
 * off-by-one lives here, where it is tested (test/liveWeekCutover.test.ts).
 *
 *   tsx scripts/liveWeek.ts field <accepted.tsv> <out field.yaml>   write the field, print its fingerprint
 *   tsx scripts/liveWeek.ts fingerprint <field.yaml>                the matrix's rosterFingerprint for it
 *   tsx scripts/liveWeek.ts images <field.yaml>                     "<id>\t<image tag>\t<dir>" per launched agent
 *   tsx scripts/liveWeek.ts keys-missing <field.yaml> <keys.yaml>   non-baseline ids with no inference key
 *   tsx scripts/liveWeek.ts pools <daemon.json>                     networks docker's address pools yield
 *   tsx scripts/liveWeek.ts restamp <plan> <start ISO> <minutes> <out>   rehearsal only: re-time a plan
 *   tsx scripts/liveWeek.ts void <matrix dir> <s> <reason>         mark a completed epoch for re-execution
 *   tsx scripts/liveWeek.ts sealed-senders                          the role keys' addresses (env), for the gateway
 *
 * The fingerprint is the runner's own (core/src/backtest/resume.ts rosterFingerprint over the
 * roster's `agents`, parsed the way `backtest --agents` parses it), so the value printed on the night
 * is the one matrix.json will carry.
 */
import { copyFileSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";
import { rosterFingerprint } from "../core/src/backtest/resume.js";
import { environmentSignerOwners } from "../core/src/realtime/environmentSigners.js";
import type { RoleKeys } from "../core/src/realtime/roleKeyGuard.js";

/** The baseline every live-week field carries (excluded from the field's mean and spread). */
export const BASELINE_ID = "noop";
/** The rule accept-submission.sh and build.sh apply to an agent id. */
export const UNIT_ID = /^[a-zA-Z0-9][a-zA-Z0-9_-]*$/;
/** Names a submission cannot take: the baseline and the runtime's reserved directories. */
export const RESERVED_UNITS = new Set([BASELINE_ID, "runtime", "lib"]);

export type AcceptedRow = {
  unit: string;
  zip: string;
  zipSha256: string;
  imageId: string;
  acceptedAt: string;
};

export const ACCEPTED_HEADER = "unit\tzip\tzipSha256\timageId\tacceptedAt";

/** accepted.tsv as cutover.sh writes it: a header line, then one tab-separated row per unit. */
export function parseAccepted(text: string): AcceptedRow[] {
  const rows: AcceptedRow[] = [];
  const seen = new Set<string>();
  text.split("\n").forEach((raw, i) => {
    const line = raw.replace(/\r$/, "");
    if (line.trim() === "" || line === ACCEPTED_HEADER) return;
    const where = `accepted.tsv line ${i + 1}`;
    const cols = line.split("\t");
    if (cols.length !== 5)
      throw new Error(`${where}: expected 5 tab-separated columns, got ${cols.length}`);
    const [unit, zip, zipSha256, imageId, acceptedAt] = cols;
    if (!UNIT_ID.test(unit)) throw new Error(`${where}: invalid unit id ${JSON.stringify(unit)}`);
    if (RESERVED_UNITS.has(unit))
      throw new Error(`${where}: ${unit} is reserved (the baseline or a runtime directory)`);
    if (seen.has(unit)) throw new Error(`${where}: ${unit} appears twice`);
    if (!/^[0-9a-f]{64}$/.test(zipSha256))
      throw new Error(`${where}: zipSha256 is not 64 lowercase hex characters`);
    if (!/^sha256:[0-9a-f]{64}$/.test(imageId))
      throw new Error(`${where}: imageId is not sha256:<64 hex>`);
    seen.add(unit);
    rows.push({ unit, zip, zipSha256, imageId, acceptedAt });
  });
  return rows;
}

/**
 * The live-week field: every accepted unit on an AUTO wallet (derived from the week's wallet
 * secret), plus the `noop` baseline. Sorted by id so the file does not depend on the order the
 * ZIPs were accepted in (the fingerprint sorts too; the sorting here is for people reading it).
 */
export function buildFieldYaml(rows: ReadonlyArray<AcceptedRow>): string {
  const units = rows.map((r) => r.unit).sort();
  const lines = [
    `# Live-week field, generated by infra/live-week/cutover.sh field from accepted.tsv (${units.length} units).`,
    "# Every wallet AUTO (derived from the week's wallet secret). Do not edit by hand: matrix.json records",
    "# this roster's fingerprint and the runner refuses a --resume on a different field.",
    "agents:",
    `  - id: ${BASELINE_ID}`,
    "    wallet: AUTO",
    "    baseline: true",
    ...units.flatMap((u) => [`  - id: ${u}`, "    wallet: AUTO"]),
  ];
  return `${lines.join("\n")}\n`;
}

type RosterEntry = {
  id?: unknown;
  dir?: unknown;
  baseline?: unknown;
  external?: unknown;
  address?: unknown;
  command?: unknown;
};

/** The `agents` array, parsed the way `backtest --agents` does (core/src/cli/backtest.ts). */
export function rosterAgents(yamlText: string): RosterEntry[] {
  const doc = parseYaml(yamlText) as { agents?: unknown } | null;
  if (!doc || !Array.isArray(doc.agents))
    throw new Error('the field must contain an "agents" array');
  return doc.agents as RosterEntry[];
}

export function fieldFingerprint(yamlText: string): string {
  return rosterFingerprint(rosterAgents(yamlText));
}

/**
 * The image each launched agent runs: run-agent.sh uses eris-agent:<basename of its agent dir>,
 * and the dir is the entry's `dir` or else its id.
 */
export function fieldImages(
  yamlText: string,
): Array<{ id: string; tag: string; dir: string }> {
  return rosterAgents(yamlText)
    .filter((a) => a.external !== true && a.address === undefined && a.command === undefined)
    .map((a) => {
      const id = String(a.id);
      const dir = typeof a.dir === "string" && a.dir !== "" ? basename(a.dir) : id;
      return { id, dir, tag: `eris-agent:${dir}` };
    });
}

/** Non-baseline agents with no entry in the inference proxy's `participants` map. */
export function keysMissing(fieldYaml: string, keysYaml: string): string[] {
  const keys = parseYaml(keysYaml) as { participants?: Record<string, unknown> } | null;
  const have = new Set(Object.keys(keys?.participants ?? {}));
  return rosterAgents(fieldYaml)
    .filter((a) => a.baseline !== true)
    .map((a) => String(a.id))
    .filter((id) => !have.has(id));
}

/**
 * How many bridge networks docker can hand out from /etc/docker/daemon.json's
 * default-address-pools (each pool `base` a.b.c.d/p split into /size subnets = 2^(size - p)).
 * 0 when the key is absent: docker then falls back to its built-in pools, which run out at about
 * the 28th agent network (infra/docker-agent/ISOLATION.md).
 */
export function poolCapacity(daemonJson: string): number {
  const doc = JSON.parse(daemonJson) as {
    "default-address-pools"?: Array<{ base?: string; size?: number }>;
  };
  const pools = doc["default-address-pools"];
  if (!Array.isArray(pools)) return 0;
  let total = 0;
  for (const p of pools) {
    const m = /^\d+\.\d+\.\d+\.\d+\/(\d+)$/.exec(String(p.base ?? ""));
    const size = Number(p.size);
    if (!m || !Number.isInteger(size))
      throw new Error(`default-address-pools entry ${JSON.stringify(p)} is malformed`);
    const prefix = Number(m[1]);
    if (size < prefix || size > 32)
      throw new Error(
        `default-address-pools entry ${JSON.stringify(p)}: size must be in [${prefix}, 32]`,
      );
    total += 2 ** (size - prefix);
  }
  return total;
}

/**
 * Rehearsal only: give the plan's epochs new start times, `minutes` apart from `start`, touching
 * nothing else in the file (the commitments and the order stay byte-identical).
 */
export function restampPlan(planText: string, startIso: string, minutes: number): string {
  const t0 = Date.parse(startIso);
  if (Number.isNaN(t0)) throw new Error(`not an ISO 8601 time: ${startIso}`);
  if (!(minutes > 0)) throw new Error(`minutes must be > 0, got ${minutes}`);
  let n = 0;
  const out = planText.replace(/^(\s+)startsAt: \S+/gm, (_m, indent: string) => {
    const t = new Date(t0 + minutes * 60_000 * n++);
    return `${indent}startsAt: ${t.toISOString()}`;
  });
  if (n === 0) throw new Error("the plan has no startsAt lines to restamp");
  return out;
}

/**
 * Rules §4.4.2 for an epoch that already completed: take its result out of matrix.json so the next
 * `--resume` runs it again with the same seed (the runner re-runs an ordinal stored with an `error`
 * and no agents, core/src/backtest/resume.ts mergeStoredResults) and restores the agents' state from
 * the checkpoint of the epoch before it. The run directory of the voided attempt stays on disk and
 * in the record (`runDir`), so the evidence is not lost. The epochs after it are not touched: whether
 * they stand is the organizer's call (resume.ts).
 */
export function voidEpoch(
  matrixText: string,
  s: number,
  reason: string,
  at: string = new Date().toISOString(),
): string {
  if (!Number.isInteger(s) || s < 1) throw new Error(`epoch ordinal must be a positive integer, got ${s}`);
  if (reason.trim() === "") throw new Error("a void needs a reason (it goes into matrix.json)");
  const m = JSON.parse(matrixText) as { schema?: unknown; scenarios?: Array<Record<string, unknown>> };
  if (m.schema !== 2 || !Array.isArray(m.scenarios))
    throw new Error("not a schema-2 matrix.json with a scenarios array");
  const entry = m.scenarios.find((r) => r.s === s);
  if (!entry) throw new Error(`matrix.json has no s=${s} (it has not run yet: nothing to void)`);
  if (!Array.isArray(entry.agents) || entry.agents.length === 0)
    throw new Error(`s=${s} has no result (already voided or failed): the next --resume re-runs it as is`);
  delete entry.agents;
  delete entry.flags;
  entry.error = `voided (rules §4.4.2): ${reason.trim()}`;
  entry.voidedAt = at;
  return `${JSON.stringify(m, null, 2)}\n`;
}

/**
 * The addresses whose pending nonce the gateway answers as of "latest" (RPC_PENDING_SEALED_SENDERS):
 * the four role keys the week runs with. The deployer sends the liquidity pull in the block a gap
 * opens, so its pending nonce named the moment one block early. All four are required: a key left
 * out would fall back to a default inside the coordinator and leave the real signer unlisted.
 */
export function sealedSenders(env: NodeJS.ProcessEnv): string {
  const names = {
    admin: "ADMIN_PRIVATE_KEY",
    keeper: "KEEPER_PRIVATE_KEY",
    setup: "SETUP_PRIVATE_KEY",
    deployer: "DEPLOYER_PRIVATE_KEY",
  } as const;
  const keys = {} as RoleKeys;
  for (const [role, name] of Object.entries(names)) {
    const v = env[name]?.trim();
    if (!v || !/^0x[0-9a-fA-F]{64}$/.test(v)) throw new Error(`${name} is not set to a private key`);
    keys[role as keyof RoleKeys] = v as RoleKeys[keyof RoleKeys];
  }
  return [...environmentSignerOwners(keys).keys()].join(",");
}

function main(argv: string[]): void {
  const [cmd, ...a] = argv;
  const read = (p: string | undefined): string => {
    if (!p) throw new Error(`missing argument for ${cmd}`);
    return readFileSync(resolve(p), "utf8");
  };
  switch (cmd) {
    case "field": {
      if (!a[1]) throw new Error("usage: liveWeek.ts field <accepted.tsv> <out field.yaml>");
      const rows = parseAccepted(read(a[0]));
      if (rows.length === 0)
        throw new Error(`${a[0]} lists no accepted unit: refusing a field with only the baseline`);
      const text = buildFieldYaml(rows);
      writeFileSync(resolve(a[1]), text);
      console.log(fieldFingerprint(text));
      return;
    }
    case "fingerprint":
      console.log(fieldFingerprint(read(a[0])));
      return;
    case "images":
      for (const i of fieldImages(read(a[0]))) console.log(`${i.id}\t${i.tag}\t${i.dir}`);
      return;
    case "keys-missing":
      for (const id of keysMissing(read(a[0]), read(a[1]))) console.log(id);
      return;
    case "pools":
      console.log(poolCapacity(read(a[0])));
      return;
    case "restamp": {
      if (!a[3]) throw new Error("usage: liveWeek.ts restamp <plan> <start ISO> <minutes> <out>");
      writeFileSync(resolve(a[3]), restampPlan(read(a[0]), a[1], Number(a[2])));
      return;
    }
    case "void": {
      const [dir, sRaw, ...why] = a;
      if (!dir || !sRaw) throw new Error("usage: liveWeek.ts void <matrix dir> <s> <reason>");
      const path = join(resolve(dir), "matrix.json");
      const next = voidEpoch(readFileSync(path, "utf8"), Number(sRaw), why.join(" "));
      const backup = `${path}.before-void-s${sRaw}-${new Date().toISOString().replace(/[:.]/g, "-")}`;
      copyFileSync(path, backup);
      writeFileSync(`${path}.tmp`, next);
      renameSync(`${path}.tmp`, path);
      console.log(`s=${sRaw} voided; the previous matrix.json is ${backup}`);
      return;
    }
    case "sealed-senders":
      console.log(sealedSenders(process.env));
      return;
    default:
      throw new Error(
        "usage: liveWeek.ts field|fingerprint|images|keys-missing|pools|restamp|void|sealed-senders ...",
      );
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
